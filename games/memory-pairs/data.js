function createRounds(rounds) {
  return Object.freeze(rounds.map((pairs) => Object.freeze(pairs.map(([
    pairId,
    leftIcon,
    leftLabel,
    rightIcon,
    rightLabel,
  ]) => Object.freeze({
    pairId,
    cards: Object.freeze([
      Object.freeze({ icon: leftIcon, label: leftLabel }),
      Object.freeze({ icon: rightIcon, label: rightLabel }),
    ]),
  })))));
}

function createWordRounds(rounds) {
  return Object.freeze(rounds.map((pairs) => Object.freeze(pairs.map(([
    pairId,
    leftIcon,
    leftLabel,
    rightIcon,
    rightLabel,
    rhymeGroup,
  ]) => Object.freeze({
    pairId,
    rhymeGroup,
    cards: Object.freeze([
      Object.freeze({ icon: leftIcon, label: leftLabel }),
      Object.freeze({ icon: rightIcon, label: rightLabel }),
    ]),
  })))));
}

